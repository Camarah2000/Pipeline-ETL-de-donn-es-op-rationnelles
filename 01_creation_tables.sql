/*Création des différentes tables */
CREATE TABLE centres_secours  (
	ID_CENTRE INTEGER NOT NULL,
	NOM_CENTRE TEXT NOT NULL,
	VILLE TEXT NOT NULL,
	CONSTRAINT ID_CENTRE PRIMARY key (ID_CENTRE)
	
  );
CREATE TABLE interventions  (
	ID INTEGER NOT NULL,
	DATE NUMERIC NOT NULL,
	CENTRE TEXT NOT NULL,
	TYPE TEXT NOT NULL,
	DUREE NUMERIC NOT NULL,
	NB_VEHICULE INTEGER NOT NULL,
	CONSTRAINT ID PRIMARY key (ID)
	
  );
  
CREATE TABLE vehicules (
	ID_VEHICULE INTEGER NOT NULL,
	CENTRE TEXT NOT NULL,
	TYPE_VEHICULE TEXT NOT NULL,
	CONSTRAINT ID_VEHICULE PRIMARY key (ID_VEHICULE)
	
  );
  
 
